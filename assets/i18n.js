export function makeT(lang) {
  const table = STRINGS[lang] || STRINGS.en;
  return (key, vars = {}, fallback) => {
    const raw = table[key] ?? STRINGS.en[key] ?? fallback;
    if (raw === undefined) {
      console.warn(`missing string: ${key}`);
      return key;
    }
    return raw.replace(/\{(\w+)\}/g, (_, k) => (vars[k] ?? `{${k}}`));
  };
}
